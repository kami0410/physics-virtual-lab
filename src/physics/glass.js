// 光学玻璃色散：Sellmeier 公式  n²(λ) = 1 + Σ Bᵢλ²/(λ² − Cᵢ)，λ 单位 µm
// 系数取自 SCHOTT 光学玻璃数据表（refractiveindex.info 收录的同一组数据），适用约 0.31–2.5 µm。
// 每组系数都用目录给出的 n_d（587.56 nm）与阿贝数 ν_d 校验过：计算值与目录值相差 < 1×10⁻⁵。

export const GLASSES = {
  'N-BK7': { kind: '硼硅酸盐冕牌玻璃（与国产 K9 相当）', B: [1.03961212, 0.231792344, 1.01046945], C: [0.00600069867, 0.0200179144, 103.560653], nd: 1.5168, vd: 64.17 },
  F2: { kind: '火石玻璃', B: [1.34533359, 0.209073176, 0.937357162], C: [0.00997743871, 0.0470450767, 111.886764], nd: 1.62004, vd: 36.37 },
  SF2: { kind: '重火石玻璃', B: [1.40301821, 0.231767504, 0.939056586], C: [0.0105795466, 0.0493226978, 112.405955], nd: 1.64769, vd: 33.85 },
  SF5: { kind: '重火石玻璃', B: [1.52481889, 0.187085527, 1.42729015], C: [0.011254756, 0.0588995392, 129.141675], nd: 1.6727, vd: 32.25 },
  'N-SF11': { kind: '重火石玻璃', B: [1.73759695, 0.313747346, 1.89878101], C: [0.013188707, 0.0623068142, 155.23629], nd: 1.78472, vd: 25.68 },
};

/** 折射率 n(λ)，λ 单位 nm；dn：熔炼批次的折射率偏差（整体平移，目录允差约 ±5×10⁻⁴） */
export function sellmeier(glass, nm, dn = 0) {
  const g = typeof glass === 'string' ? GLASSES[glass] : glass;
  const L = (nm / 1000) ** 2;
  let s = 1;
  for (let i = 0; i < 3; i++) s += (g.B[i] * L) / (L - g.C[i]);
  return Math.sqrt(s) + dn;
}

/** 夫琅禾费谱线波长 nm：d（氦黄线）、F（氢蓝线）、C（氢红线）、D（钠双线平均） */
export const FRAUNHOFER = { d: 587.56, F: 486.13, C: 656.27, D: 589.29 };

/** 阿贝数 ν_d = (n_d − 1)/(n_F − n_C) */
export function abbeNumber(glass, dn = 0) {
  const n = (nm) => sellmeier(glass, nm, dn);
  return (n(FRAUNHOFER.d) - 1) / (n(FRAUNHOFER.F) - n(FRAUNHOFER.C));
}
